"""Check ``job_config`` keys LHP also writes into job resources (#351).

LHP writes ``name`` and ``tasks`` into every orchestration and monitoring job
resource and passes every other ``job_config`` key through verbatim. A user
value for one of those keys used to come out as a second key of the same
name, and YAML readers keep the last one, so LHP's value was silently
discarded. ``tasks`` are now appended after the generated tasks, so their
shape is checked here; ``name`` is LHP-owned and rejected. Every failure is
``LHP-CFG-072``.
"""

import logging
from typing import Any, Collection, Mapping, Set

from ._resource_key_errors import owned_key_error, resource_key_error

logger = logging.getLogger(__name__)

#: Keys job_resource.yml.j2 and monitoring_job_resource.yml.j2 write
#: themselves. JobGenerator keeps them out of the templates' pass-through loop,
#: so a user value is never emitted twice.
LHP_WRITTEN_JOB_KEYS = frozenset({"name", "tasks"})

_TASK_EXAMPLE = (
    "tasks:\n"
    "  - task_key: notify\n"
    "    depends_on:\n"
    "      - task_key: <pipeline>_pipeline\n"
    "    notebook_task:\n"
    "      notebook_path: ${workspace.file_path}/notebooks/notify"
)

_NAME_REASON = (
    "LHP names every job resource after its job: the flowgroups' 'job_name', "
    "the project name for the default orchestration job, or the monitoring "
    "pipeline for the monitoring job."
)
_NAME_FIX = "Remove 'name'. To change the name, change the flowgroups' 'job_name'."


def validate_job_resource_keys(
    config: Mapping[str, Any],
    *,
    job_name: str,
    generated_task_keys: Collection[str],
) -> None:
    """Check one resolved job config's LHP-written keys before it renders.

    Args:
        config: The job config the template renders (defaults merged).
        job_name: The job resource name, for the error message.
        generated_task_keys: The ``task_key`` of every task LHP generates
            for this job; a user task may depend on them but not reuse them.

    Raises:
        LHPConfigError: ``LHP-CFG-072`` if the config sets ``name``, or a
            ``tasks`` value that is not a list of mappings with distinct,
            non-empty string ``task_key`` values unused by generated tasks.
    """
    if "name" in config:
        raise owned_key_error("job_config", "name", _NAME_REASON, _NAME_FIX, job_name)
    if "tasks" in config:
        _check_tasks(config["tasks"], job_name, generated_task_keys)


def _check_tasks(
    tasks: Any, job_name: str, generated_task_keys: Collection[str]
) -> None:
    if not isinstance(tasks, list):
        raise resource_key_error(
            title="Job 'tasks' must be a list of tasks",
            details=(
                f"'tasks' for job '{job_name}' must be a list, got "
                f"{type(tasks).__name__}. LHP appends these tasks after the "
                f"pipeline tasks it generates."
            ),
            suggestions=["List each extra task as a '- task_key:' entry"],
            example=_TASK_EXAMPLE,
            context={"Job": job_name},
        )
    generated = set(generated_task_keys)
    seen: Set[str] = set()
    for index, task in enumerate(tasks):
        task_key = task.get("task_key") if isinstance(task, dict) else None
        if not isinstance(task_key, str) or not task_key.strip():
            raise resource_key_error(
                title=f"Job task {index} has no 'task_key'",
                details=(
                    f"Task {index} in 'tasks' for job '{job_name}' must be a "
                    f"mapping with a non-empty string 'task_key', got {task!r}."
                ),
                suggestions=["Give every task a unique 'task_key'"],
                example=_TASK_EXAMPLE,
                context={"Job": job_name, "Task": index},
            )
        if task_key in generated:
            raise resource_key_error(
                title=f"Job task key '{task_key}' is generated by LHP",
                details=(
                    f"Task '{task_key}' in 'tasks' for job '{job_name}' reuses "
                    f"the key of a task LHP generates. Generated task keys: "
                    f"{', '.join(sorted(generated))}."
                ),
                suggestions=[
                    "Rename the task; to run it after a generated task, list "
                    "that task's key under 'depends_on'"
                ],
                example=_TASK_EXAMPLE,
                context={"Job": job_name, "Task": index},
            )
        if task_key in seen:
            raise resource_key_error(
                title=f"Job task key '{task_key}' is used twice",
                details=(
                    f"'tasks' for job '{job_name}' lists task_key '{task_key}' "
                    f"more than once; Databricks requires unique task keys."
                ),
                suggestions=["Give every task a unique 'task_key'"],
                context={"Job": job_name, "Task": index},
            )
        seen.add(task_key)
