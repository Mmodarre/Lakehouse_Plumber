"""The assembled module header escapes the pipeline and flowgroup names (#296).

:class:`CodeAssembler` writes both names into ``# Pipeline:`` /
``# FlowGroup:`` comment lines and into the ``PIPELINE_ID`` /
``FLOWGROUP_ID`` string literals. A backslash sequence, a quote or a line
break in a name must not change the literal's value, break the module, or
turn part of a comment into code. A valid name keeps the exact header bytes.
"""

from __future__ import annotations

import ast

import pytest

from lhp.core.codegen.assembler import CodeAssembler
from lhp.models import FlowGroup

pytestmark = pytest.mark.unit

_BODY = "x = 1\n"


def _assemble(pipeline: str, flowgroup: str) -> str:
    return CodeAssembler().assemble(
        FlowGroup(pipeline=pipeline, flowgroup=flowgroup), set(), set(), _BODY
    )


def _module_constants(code: str) -> dict[str, object]:
    tree = ast.parse(code)
    return {
        node.targets[0].id: ast.literal_eval(node.value)
        for node in tree.body
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name)
    }


def test_valid_names_keep_the_exact_header_bytes():
    code = _assemble("bronze", "orders_fg")

    assert code == (
        "# Generated by LakehousePlumber\n"
        "# Pipeline: bronze\n"
        "# FlowGroup: orders_fg\n"
        "\n"
        "\n"
        "\n"
        "# Pipeline Configuration\n"
        'PIPELINE_ID = "bronze"\n'
        'FLOWGROUP_ID = "orders_fg"\n'
        "\n"
        "\n" + _BODY
    )


@pytest.mark.parametrize(
    ("pipeline", "flowgroup"),
    [
        ("p\\new", "fg\\new"),
        ("p\\x41", "fg\\N{BULLET}"),
        ('say "hi"', 'fg"q'),
        ("trailing\\", "fg\\"),
        ("C:\\temp\\new", "\\\\server\\share"),
    ],
)
def test_ids_round_trip_backslashes_and_quotes(pipeline, flowgroup):
    constants = _module_constants(_assemble(pipeline, flowgroup))

    assert constants["PIPELINE_ID"] == pipeline
    assert constants["FLOWGROUP_ID"] == flowgroup
    assert constants["x"] == 1


def test_line_break_in_a_name_stays_in_the_comment_and_the_literal():
    code = _assemble("p\nimport os", "fg\nos.system('x')")

    constants = _module_constants(code)
    assert constants["PIPELINE_ID"] == "p\nimport os"
    assert constants["FLOWGROUP_ID"] == "fg\nos.system('x')"
    tree = ast.parse(code)
    assert not any(isinstance(node, (ast.Import, ast.Expr)) for node in tree.body)
    assert "# Pipeline: p\n# import os\n" in code
    assert "# FlowGroup: fg\n# os.system('x')\n" in code
